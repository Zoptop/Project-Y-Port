#!/usr/bin/env python3
"""Ground truth for the port's CPlayer / CPlayerKI: runs the original's AI
influence map, fog-of-war and radar functions under emulation on the real
state of a freshly started skirmish (player 2 = AI) and writes the inputs and
results as a C++ header that tests/test_players.cpp checks the port against.

    PYTHONPATH=<unicorn>/bindings/python:tools/emu python3 tools/emu/ai_oracle.py \\
        --data data --maps 1 4 --out tests/players_oracle_data.h

Scenario per map (start_game with 3 players, UseFOW on):
  1. CPlayerKI::oneTimeInit                 -> influence grid (BLOCKED layers)
  2. CPlayerKI::updateInfluenceUnits        -> unit layers (also every unit's
     getInfluenceAndFalloff, to tell the port's unit state apart)
  3. flagposts' Life/Lifedot (+0x350/+0x354) set to 0, updateInfluenceGoal
  4. synthetic INFLUENCE values, updateInfluenceGoal (GOAL/SUM only)
  5. updateInfluenceMapWithFalloff with random arguments into every layer
  6. getInfluenceIndexFromMapPosition at random positions
  7. human player 1: drawFOWCirclePlayer / FOWtimeupdate / addRadar /
     removeRadar / getVisibilityValue
"""
from __future__ import annotations

import argparse
import os
import random
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from game_oracle import Oracle  # noqa: E402

KI = '_ZN8ProjectY9CPlayerKI'
PL = '_ZN8ProjectY7CPlayer'


def f2b(f: float) -> int:
    return struct.unpack('<I', struct.pack('<f', f))[0]


def b2f(b: int) -> float:
    return struct.unpack('<f', struct.pack('<I', b & 0xffffffff))[0]


def fnv(words) -> int:
    h = 0x811c9dc5
    for w in words:
        for k in range(4):
            h ^= (w >> (8 * k)) & 0xff
            h = (h * 0x01000193) & 0xffffffff
    return h


class AI:
    def __init__(self, o: Oracle, ai: int):
        self.o, self.e, self.ai = o, o.emu, ai

    def grid(self):
        e, ai = self.e, self.ai
        w, h, base = e.read_u32(ai + 0x150), e.read_u32(ai + 0x154), e.read_u32(ai + 0x158)
        cells = []
        for i in range(w * h):
            c = base + 0x28 * i
            cells.append([e.read_u32(c)] + [e.uc.mem_read(c + 4, 1)[0]] + [e.read_u32(c + o) for o in range(8, 0x28, 4)])
        return w, h, cells

    def set_layer(self, off, values):
        base = self.e.read_u32(self.ai + 0x158)
        for i, v in enumerate(values):
            self.o.w32(base + 0x28 * i + off, v)


def map_players(data: str, map_id: int) -> int:
    for line in open(os.path.join(data, 'map%dEnglish.txt' % map_id), encoding='latin-1'):
        if line.startswith('set numplayers'):
            return int(line.split()[2])
    return 2


def objects(o: Oracle):
    e, g = o.emu, o.game
    objs = e.read_u32(g + 0x48)
    for oid in o._list(g + 0x78):
        obj = e.read_u32(objs + 4 * oid)
        if obj:
            yield oid, obj


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--so', default='/home/claude/out/ProjectY_engine_RE/libProjectY.so')
    ap.add_argument('--data', default='data')
    ap.add_argument('--maps', type=int, nargs='+', default=[1, 4])
    ap.add_argument('--out', default='tests/players_oracle_data.h')
    ap.add_argument('--seed', type=int, default=7)
    a = ap.parse_args()
    out = ['// Generated by tools/emu/ai_oracle.py from the original engine under emulation.',
           '// Do not edit. Floats are bit patterns.', '#pragma once', '#define PLAYERS_ORACLE_SQUADS 1', '#include <cstdint>', '',
           'namespace players_oracle {', '']
    for map_id in a.maps:
        rng = random.Random(a.seed * 1000 + map_id)
        o = Oracle(a.so, a.data)
        e = o.emu
        engine = o.call('_ZN8ProjectY7CEngine15getSingletonPtrEv')
        o.call('_ZN8ProjectY7CEngine4initEv', engine, max_insns=2_000_000_000)
        # [!] with UseFOW the original's "set fowsize" initialises players
        # 0..numplayers of the map and crashes if fewer exist: at least the
        # map's player count, and 3 so that player 2 is an AI
        nplayers = max(3, map_players(a.data, map_id))
        o.start_game(engine, map_id, nplayers, fow=1)
        out.append('const unsigned m%d_players = %d;' % (map_id, nplayers))
        players = dict(o._map_values(o.game + 0x10))
        ki = AI(o, players[2])
        level = e.read_u32(o.game + 0xa4)
        map_w, map_h = b2f(e.read_u32(level + 0xc0)), b2f(e.read_u32(level + 0xc4))
        P = 'm%d_' % map_id
        print('map', map_id, 'size', map_w, map_h, file=sys.stderr)

        def emit_grid(name, cells):
            out.append('const uint32_t %s%s[] = {' % (P, name))
            for c in cells:
                out.append('    ' + ', '.join('0x%08x' % v for v in c) + ',')
            out.append('};')

        # 1. grid + blocked layers
        o.call(KI + '11oneTimeInitEv', ki.ai)
        w, h, cells = ki.grid()
        out.append('const unsigned %sW = %d, %sH = %d;' % (P, w, P, h))
        emit_grid('blocked', cells)

        # 2. units
        scratch = e.malloc(64)
        units = []
        for oid, obj in objects(o):
            if e.read_u32(obj + 0xd0) != 1:
                continue
            o.call(e.read_u32(e.read_u32(obj) + 0x100), obj, scratch, scratch + 4, scratch + 8)
            owner = e.read_u32(obj + 0x1f8)
            pid = e.read_u32(owner + 0x1c) if owner else 0xffffffff
            units.append([oid, e.read_u32(obj + 0xd4), pid, e.read_u32(obj + 0x90), e.read_u32(obj + 0x94),
                          e.read_u32(scratch), e.read_u32(scratch + 4), e.read_u32(scratch + 8)])
        out.append('// id, type, owner, x, y, influence, falloff, radius')
        out.append('const uint32_t %sunits[][8] = {' % P)
        for u in units:
            out.append('    {' + ', '.join('0x%08x' % v for v in u) + '},')
        out.append('};')
        o.call(KI + '20updateInfluenceUnitsEv', ki.ai)
        emit_grid('unitgrid', ki.grid()[2])

        # buildings (the goal layer's input)
        blds = []
        for oid, obj in objects(o):
            if e.read_u32(obj + 0xd0) == 2:
                owner = e.read_u32(obj + 0x1f8)
                blds.append([oid, e.read_u32(obj + 0xd4), e.read_u32(owner + 0x1c) if owner else 0xffffffff,
                             e.read_u32(obj + 0x90), e.read_u32(obj + 0x94)])
        out.append('// buildings: id, type, owner, x, y')
        out.append('const uint32_t %sbuildings[][5] = {' % P)
        for b in blds:
            out.append('    {' + ', '.join('0x%08x' % v for v in b) + '},')
        out.append('};')

        # 3. goal with every flag at Life 0 / Lifedot 0
        for oid, obj in objects(o):
            if e.read_u32(obj + 0xd0) == 2 and e.read_u32(obj + 0xd4) == 1:
                o.w32(obj + 0x350, 0)
                o.w32(obj + 0x354, 0)
        o.call(KI + '19updateInfluenceGoalEv', ki.ai)
        emit_grid('goal', ki.grid()[2])

        # 4. synthetic influence (cases: mixed signs, all >= 0, all <= 0, zero)
        for case in range(4):
            if case == 0:
                vals = [f2b(rng.uniform(-300, 300)) for _ in range(w * h)]
            elif case == 1:
                vals = [f2b(rng.uniform(0, 300)) for _ in range(w * h)]
            elif case == 2:
                vals = [f2b(-rng.uniform(0, 300)) for _ in range(w * h)]
            else:
                vals = [0] * (w * h)
            ki.set_layer(0x14, vals)
            o.call(KI + '19updateInfluenceGoalEv', ki.ai)
            out.append('const uint32_t %ssynth%d_in[] = {%s};' % (P, case, ', '.join('0x%08x' % v for v in vals)))
            emit_grid('synth%d' % case, ki.grid()[2])

        # 5. falloff splats, cumulative, into layers 1..11 (2 = the BLOCKED quirk)
        ki.set_layer(0, [0] * (w * h))
        for off in range(8, 0x28, 4):
            ki.set_layer(off, [0] * (w * h))
        pos = e.malloc(8)
        splats = []
        for k in range(120):
            value = rng.choice([rng.uniform(0.5, 400), rng.uniform(-50, 5), 5.0, 0.0])
            falloff = rng.choice([0.0, rng.uniform(1, 300), 200.0])
            radius = rng.choice([rng.uniform(0, 300), 100.0, -10.0])
            x = rng.uniform(-0.7 * map_w, 0.7 * map_w)
            y = rng.uniform(-0.7 * map_h, 0.7 * map_h)
            m = rng.randint(1, 11)
            args = [f2b(value), f2b(falloff), f2b(radius), f2b(x), f2b(y), m]
            e.uc.mem_write(pos, struct.pack('<II', args[3], args[4]))
            o.call(KI + '29updateInfluenceMapWithFalloffEfffRKNS_8CVector2ENS_14EInfluenceMapsE',
                   ki.ai, args[0], args[1], args[2], pos, m)
            splats.append(args)
        out.append('// value, falloff, radius, x, y, map')
        out.append('const uint32_t %ssplats[][6] = {' % P)
        for s in splats:
            out.append('    {' + ', '.join('0x%08x' % v for v in s) + '},')
        out.append('};')
        emit_grid('splat', ki.grid()[2])

        # 6. index lookups
        idx = []
        for k in range(200):
            x = rng.uniform(-0.8 * map_w, 0.8 * map_w)
            y = rng.uniform(-0.8 * map_h, 0.8 * map_h)
            e.uc.mem_write(pos, struct.pack('<ff', x, y))
            r = o.call(KI + '32getInfluenceIndexFromMapPositionERKNS_8CVector2E', ki.ai, pos)
            idx.append([f2b(x), f2b(y), r & 0xffffffff])
        out.append('const uint32_t %sindex[][3] = {' % P)
        for r in idx:
            out.append('    {0x%08x, 0x%08x, %d},' % tuple(r))
        out.append('};')

        # 7. FOW / radar of the human player 1
        p1 = players[1]
        fw, fh = e.read_u32(level + 0x168), e.read_u32(level + 0x16c)
        out.append('const unsigned %sfowW = %d, %sfowH = %d;' % (P, fw, P, fh))
        ops = []
        fowgrid = lambda: list(e.uc.mem_read(e.read_u32(p1 + 0x80), fw * fh))
        radgrid = lambda: list(e.uc.mem_read(e.read_u32(p1 + 0x11c), fw * fh))
        radar_ids = []
        for k in range(60):
            kind = rng.choice(['circle', 'circle', 'fade', 'radar', 'unradar'])
            dt = rng.choice([0.0999985, 0.016, 0.2, 0.05])
            o.w32(engine + 0x1a8, f2b(dt))
            x = rng.uniform(-0.6 * map_w, 0.6 * map_w)
            y = rng.uniform(-0.6 * map_h, 0.6 * map_h)
            r = rng.uniform(0, 250)
            e.uc.mem_write(pos, struct.pack('<ff', x, y))
            if kind == 'circle':
                o.call(PL + '19drawFOWCirclePlayerERKNS_8CVector2Ef', p1, pos, f2b(r))
            elif kind == 'fade':
                o.call(PL + '13FOWtimeupdateEv', p1)
            elif kind == 'radar':
                rid = rng.randint(1100, 1110)
                radar_ids.append(rid)
                o.call(PL + '8addRadarERKNS_8CVector2Efj', p1, pos, f2b(r), rid)
            else:
                if not radar_ids:
                    continue
                rid = radar_ids.pop(rng.randrange(len(radar_ids)))
                if rid in radar_ids:   # removed twice would crash the original
                    radar_ids = [i for i in radar_ids if i != rid]
                o.call(PL + '11removeRadarEj', p1, rid)
            ops.append([['circle', 'fade', 'radar', 'unradar'].index(kind), f2b(dt), f2b(x), f2b(y), f2b(r),
                        rid if kind in ('radar', 'unradar') else 0, fnv(fowgrid()), fnv(radgrid())])
        out.append('// kind (0 circle, 1 fade, 2 addRadar, 3 removeRadar), dt, x, y, r, radar id, fnv(fow), fnv(radar)')
        out.append('const uint32_t %sfowops[][8] = {' % P)
        for op in ops:
            out.append('    {' + ', '.join('0x%08x' % v for v in op) + '},')
        out.append('};')
        out.append('const uint32_t %sfowfinal[] = {%s};' % (P, ', '.join(str(v) for v in fowgrid())))
        vis = []
        bptr = e.malloc(4)
        for k in range(150):
            x = rng.uniform(-0.6 * map_w, 0.6 * map_w)
            y = rng.uniform(-0.6 * map_h, 0.6 * map_h)
            e.uc.mem_write(pos, struct.pack('<ff', x, y))
            o.w32(bptr, 0)
            v = o.call(PL + '18getVisibilityValueERKNS_8CVector2EPb', p1, pos, bptr)
            vis.append([f2b(x), f2b(y), v & 0xffffffff, e.uc.mem_read(bptr, 1)[0]])
        out.append('const uint32_t %svis[][4] = {' % P)
        for v in vis:
            out.append('    {' + ', '.join('0x%08x' % x for x in v) + '},')
        out.append('};')

        # 8. squads and strategy: AI vehicles (no driver) with chosen influence
        # (+0x13a4), synthetic INFLUENCE / SUM layers; rounds of updateSquads +
        # updateStrategy in different modes. The unit fields the squad logic
        # reads are recorded so the test can give the port's units the same.
        # The AI's commands go through the game's command manager (game+0x178),
        # which the headless start does not create: give it the single-player one.
        cm = e.read_u32(o.game + 0x178)
        try:
            ok = cm != 0 and e.read_u32(e.read_u32(cm)) != 0
        except Exception:
            ok = False
        if not ok:
            cm = e.malloc(0x40)
            e.uc.mem_write(cm, b'\0' * 0x40)
            o.call('_ZN8ProjectY20CCommandManagerLocalC1Ev', cm)
            o.w32(o.game + 0x178, cm)
            print('installed CCommandManagerLocal', file=sys.stderr)
        fac = o.call('_ZN8ProjectY12CUnitFactory15getSingletonPtrEv')
        made = []
        for k in range(16):
            t = rng.choice([2, 3, 5, 10, 9, 12, 13, 16, 19])
            x = rng.uniform(-0.35 * map_w, 0.35 * map_w)
            y = rng.uniform(-0.35 * map_h, 0.35 * map_h)
            u = o.call('_ZN8ProjectY12CUnitFactory10createUnitEijfffbj', fac, t, 2, f2b(x), f2b(y), 0, 0, 0)
            o.w32(u + 0x13a4, f2b(rng.choice([rng.uniform(1, 400), 0.0])))
            made.append([e.read_u32(u + 0xf0), t, f2b(x), f2b(y)])
        out.append('// created units: id, type, x, y')
        out.append('const uint32_t %ssq_made[][4] = {' % P)
        for m in made:
            out.append('    {' + ', '.join('0x%08x' % v for v in m) + '},')
        out.append('};')
        infl = [f2b(rng.uniform(-400, 300)) for _ in range(w * h)]
        sums = [f2b(rng.uniform(0, 2)) for _ in range(w * h)]
        ki.set_layer(0x14, infl)
        ki.set_layer(0x24, sums)
        out.append('const uint32_t %ssq_infl[] = {%s};' % (P, ', '.join('0x%08x' % v for v in infl)))
        out.append('const uint32_t %ssq_sum[] = {%s};' % (P, ', '.join('0x%08x' % v for v in sums)))
        # the AI's units as the squad code sees them
        ufields = []
        for oid, _ in o._map_values(ki.ai + 0x34):
            obj = e.read_u32(e.read_u32(o.game + 0x48) + 4 * oid)
            if not obj:
                continue
            ufields.append([oid, e.read_u32(obj + 0xd4), e.read_u32(obj + 0xeac), e.read_u32(obj + 0x5c),
                            e.uc.mem_read(obj + 0x151c, 1)[0], e.read_u32(obj + 0x90), e.read_u32(obj + 0x94),
                            e.read_u32(obj + 0x13a4)])
        out.append('// AI units: id, type, unit state, flags, script controlled, x, y, influence')
        out.append('const uint32_t %ssq_units[][8] = {' % P)
        for u in ufields:
            out.append('    {' + ', '.join('0x%08x' % v for v in u) + '},')
        out.append('};')
        rounds = []
        for rnd, mode in enumerate([0, 0, 0, 2, 1, 0]):
            o.w32(ki.ai + 0x14c, mode)
            if mode == 2:   # target position
                o.w32(ki.ai + 0x1c4, 2)
                o.w32(ki.ai + 0x1d0, f2b(rng.uniform(-200, 200)))
                o.w32(ki.ai + 0x1d4, f2b(rng.uniform(-200, 200)))
            r1 = o.call(KI + '12updateSquadsEv', ki.ai)
            r2 = o.call(KI + '14updateStrategyEv', ki.ai)
            row = [mode, r1, r2, e.read_u32(ki.ai + 0x1a8), e.read_u32(ki.ai + 0x1b4), e.read_u32(ki.ai + 0x1b8),
                   e.read_u32(ki.ai + 0x174), e.read_u32(ki.ai + 0x1c4), e.read_u32(ki.ai + 0x1d0),
                   e.read_u32(ki.ai + 0x1d4)]
            squads = []
            for sq, _ in o._map_values(ki.ai + 0x17c):
                ids = [v for v, _ in o._map_values(sq + 0x10)]
                squads.append([e.read_u32(sq + 4), e.read_u32(sq + 0x20), e.read_u32(sq + 0x24), e.read_u32(sq + 0x28),
                               e.read_u32(sq + 0x2c), e.read_u32(sq + 0x30), e.uc.mem_read(sq + 0x34, 1)[0],
                               e.read_u32(sq + 0x38), e.read_u32(sq + 0x3c), fnv(ids)])
            rounds.append((row, squads))
        out.append('// rounds: mode, ret squads, ret strategy, maxPerSquad, wanted, current, lastId, targetMode, tx, ty')
        out.append('// then per squad: id, count, state, strength, target x, y, hasTarget, pos x, y, fnv(unit ids)')
        for i, (row, squads) in enumerate(rounds):
            out.append('const uint32_t %ssq_round%d[] = {%s};' % (P, i, ', '.join('0x%08x' % v for v in row)))
            out.append('const uint32_t %ssq_round%d_squads[][10] = {' % (P, i))
            for s in squads:
                out.append('    {' + ', '.join('0x%08x' % v for v in s) + '},')
            if not squads:
                out.append('    {0},')
            out.append('};')
            out.append('const unsigned %ssq_round%d_n = %d;' % (P, i, len(squads)))
        out.append('')
    out.append('}  // namespace players_oracle')
    with open(a.out, 'w') as f:
        f.write('\n'.join(out) + '\n')
    print('wrote', a.out, file=sys.stderr)


if __name__ == '__main__':
    main()
